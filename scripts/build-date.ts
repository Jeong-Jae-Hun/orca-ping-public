import { build } from 'esbuild'
import { copyFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
mkdirSync(join(root, 'vendor'), { recursive: true })
await build({
  stdin: { contents: "export { addDays, addHours, set, differenceInMinutes } from 'date-fns'; export { fromZonedTime, toZonedTime } from 'date-fns-tz';", resolveDir: root },
  outfile: join(root, 'vendor/date.js'), bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', minify: true,
  banner: { js: '// Generated by scripts/build-date.ts. date-fns/date-fns-tz: MIT; licenses are in this folder.' },
})
copyFileSync(join(root, 'node_modules/date-fns/LICENSE.md'), join(root, 'vendor/date-fns.LICENSE.md'))
copyFileSync(join(root, 'node_modules/date-fns-tz/LICENSE.md'), join(root, 'vendor/date-fns-tz.LICENSE.md'))

await build({ stdin: { contents: "export { z } from 'zod';", resolveDir: root }, outfile: join(root, 'vendor/schema.js'), bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', minify: true })
copyFileSync(join(root, 'node_modules/zod/LICENSE'), join(root, 'vendor/zod.LICENSE'))
